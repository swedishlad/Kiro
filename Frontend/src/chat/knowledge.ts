/** Reads every input from Backend/data; `read` takes a path relative to that folder. */
export function readKnowledgeInputs(read: (path: string) => string): KnowledgeInputs {
  const json = <T>(p: string) => JSON.parse(read(p)) as T;
  return {
    eia: parseEia(read("build/eia_ma_monthly.csv")),
    monthlyRates: parseMonthlyRates(read("snapshot/monthly_residential_cents_2026-07-02.csv")),
    fixedRates: parseFixedRates(read("snapshot/fixed_residential_cents_2026-07-02.csv")),
    towns: parseTowns(read("build/ma_towns.csv")),
    recs: parseRecs(read("build/recs_ma.csv")),
    consumptionStats: json("build/consumption_stats.json"),
    savingsModel: json("build/savings_model.json"),
    hmm: json("build/hmm_regimes.json"),
    mapConsumption: json("build/map_consumption.json"),
    regimes: json("build/regimes.json"),
    forecast: json("build/mc_forecast.json"),
  };
}

/** The generated TypeScript module the chat endpoint imports (server/knowledge.ts). */
export function knowledgeModule(markdown: string): string {
  const body = markdown.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
  return [
    "// GENERATED by `npm run knowledge` from Backend/data. Do not edit by hand: change src/chat/knowledge.ts.",
    "// The Watt If assistant's knowledge base; src/chat/knowledge.test.ts fails when it is out of date.",
    "",
    `export const KNOWLEDGE = \`${body}\`;`,
    "",
  ].join("\n");
}

// ----------------------------------------------------------------------------- helpers

function table(head: string[], rows: (string | number)[][]): string {
  return [`| ${head.join(" | ")} |`, `|${head.map(() => "---").join("|")}|`, ...rows.map((r) => `| ${r.join(" | ")} |`)].join("\n");
}

const RANGE_WORD: Record<GridColor, string> = { green: "Below range", grey: "Within range", red: "Above range" };
const LEVEL_WORD: Record<RegimeName, string> = { GREEN: "Low", GREY: "Mid", RED: "High" };

/** "−5.7%" from a percentage value (regimes.json stores percentages, not fractions). */
const pctPoints = (v: number) => fmtSignedPct(v / 100);
/** below / within / above probabilities as "34% / 58% / 8%". */
const odds = (p: number[]) => p.map((x) => fmtPct(x)).join(" / ");
const cents = (c: number | null, digits = 3) => (c === null ? "—" : fmtNum(c, digits));

/** regimes.json carries a few fields the pages don't read. */
type RegimeArea = Omit<GridArea, "outlook"> & {
  outlook: { days: number; probs: number[]; method?: string }[];
  forecast?: { date: string; probs: number[]; color: GridColor; method: string }[];
};

