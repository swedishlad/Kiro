function yearsSection(d: KnowledgeInputs): string {
  const years = calendarYears(d.eia);
  const lastFull = years[years.length - 1].year;
  const ytdRows = d.eia.filter((m) => m.year > lastFull);
  const rows = years.map((y) => [y.year, fmtNum(y.priceCents, 2), fmtNum(y.salesGwh), fmtNum(y.avgCustomers), fmtNum(y.kwhPerAccount)]);
  let ytd = "";
  if (ytdRows.length) {
    const revenue = ytdRows.reduce((s, r) => s + r.revenueKusd, 0);
    const sales = ytdRows.reduce((s, r) => s + r.salesMwh, 0);
    ytd = `\n\n${ytdRows[0].year} so far (${ymLabel(ytdRows[0].ym)} – ${ymLabel(ytdRows[ytdRows.length - 1].ym)}, preliminary): ${fmtNum((revenue / sales) * 100, 2)}¢/kWh average price, ${fmtNum(sales / 1000)} GWh sold.`;
  }
  return `## Price and use by calendar year (EIA-861M, all residential customers)

Average price = revenue ÷ sales for the year (EIA's definition), never an average of monthly prices.

${table(["Year", "Avg price ¢/kWh", "Sales GWh", "Avg accounts", "kWh per account"], rows)}${ytd}`;
}

function monthlySection(d: KnowledgeInputs): string {
  const level = new Map(d.hmm.timeline.map((t) => [t.period, t.regime]));
  const homes = d.regimes.areas.find((a) => a.area === "MA_RES")!;
  const range = new Map(homes.timeline.map((t) => [t.date.slice(0, 7), t]));
  const rows = d.eia.map((m) => {
    const r = range.get(m.ym);
    const lv = level.get(m.ym);
    return [
      `${ymLabel(m.ym)}${m.preliminary ? "*" : ""}`,
      fmtNum(m.priceCents, 2),
      fmtNum(m.kwhPerCustomer),
      fmtNum(m.customers),
      lv ? LEVEL_WORD[lv] : "—",
      r ? `${RANGE_WORD[r.color]} (${pctPoints(r.pctVsAverage)})` : "—",
    ];
  });
  return `## Month by month (EIA-861M, statewide residential)

* = preliminary. "Use regime" is the Low / Mid / High level model; "Homes vs usual range" compares the month with the same month in the previous 5 years (from ${ymLabel(homes.timeline[0].date.slice(0, 7))}).

${table(["Month", "Avg price ¢/kWh", "kWh per account", "Accounts", "Use regime", "Homes vs usual range"], rows)}`;
}

function ratesSection(d: KnowledgeInputs): string {
  const { savingsModel: sm, monthlyRates } = d;
  const spans = termSpans(d.fixedRates);
  const [termFrom, termTo] = sm.basicServiceRatesCents.term.split("..");
  const fixed = UTILITIES.map((u) => {
    const terms = [...spans[u.id]].reverse().map((s) => `- ${s.start === s.end ? ymLabel(s.end) : `${ymLabel(s.start)} – ${ymLabel(s.end)}`}: ${fmtNum(s.cents, 3)}¢`);
    return `### ${u.name}: fixed-option terms, newest first\n\n${terms.join("\n")}`;
  });
  const months = monthlyRates.NG.map((p) => p.ym);
  const monthly = months.map((m, i) => [ymLabel(m), ...UTILITIES.map((u) => cents(monthlyRates[u.id][i].cents))]);
  return `## Basic service rates (residential supply only, ¢/kWh; Mass.gov DPU, retrieved 2 Jul 2026)

Utilities: ${UTILITIES.map((u) => `${u.name}: ${u.detail}`).join("; ")}. The data does not say which utility serves which town; the utility's name is on the customer's bill.

Current fixed-option term, ${ymLabel(termFrom)} – ${ymLabel(termTo)}:

${table(["Utility", "¢/kWh"], UTILITIES.map((u) => [u.name, fmtNum(sm.basicServiceRatesCents[u.id], 3)]))}

A fixed rate covers the months since the previous term ended. The savings calculator compares against these fixed-option rates.

${fixed.join("\n\n")}

### Monthly (variable) option by month

Published through ${ymLabel(months[months.length - 1])}. Eversource East (then NSTAR) has no monthly values before 2007.

${table(["Month", ...UTILITIES.map((u) => u.name)], monthly)}`;
}

function savingsSection(d: KnowledgeInputs): string {
  const spans = termSpans(d.fixedRates);
  const windows = UTILITIES.map((u) => {
    const w = coveredWindow(spans, u.id);
    return `${u.name} ${ymLabel(w.first)} – ${ymLabel(w.last)}`;
  });
  const examples = d.savingsModel.examples.map((ex) => {
    const n = ex.months.length;
    const when = n > 1 ? `${ymLabel(ex.months[0])} – ${ymLabel(ex.months[n - 1])}` : ymLabel(ex.months[0]);
    return `- ${utilityById(ex.utility).name}, ${when} (${n} month${n > 1 ? "s" : ""}), ${fmtNum(ex.kwhByMonth[0])} kWh a month at ${fmtNum(ex.userRateCents, 1)}¢ vs basic service ${fmtNum(ex.basicServiceCentsByMonth[0], 3)}¢: (${fmtNum(ex.basicServiceCentsByMonth[0], 3)} − ${fmtNum(ex.userRateCents, 1)}) × ${fmtNum(ex.kwhByMonth[0])} ÷ 100 = ${ex.savedMonthlyDisplay[0]} a month; total **${ex.savedTotalDisplay}**.`;
  });
  return `## The savings calculator ("Did your supplier save you money?", Prices & savings tab)

- Formula, per month: saved = (basic-service fixed rate − your supply rate) × kWh ÷ 100, in dollars, using the fixed-option rate of the term that covers that month for the chosen utility. Totals add the months, rounded half-up to the cent for display.
- Positive = the competitive rate beat basic service (saved); negative = basic service would have been cheaper (overpaid).
- Supply portion only: delivery charges are the same either way, so they cancel out.
- The supply rate is on the bill's "Supply" or "Generation" line, in ¢/kWh (a rate shown in $/kWh such as 0.152 is 15.2¢).
- Months the calculator can cover: ${windows.join("; ")}.
- "Annual kWh, spread by season" splits a yearly total with the statewide monthly shares (see the use section below).

Worked examples from the backend (the calculator reproduces them to the cent):
${examples.join("\n")}`;
}

function useSection(d: KnowledgeInputs): string {
  const { consumptionStats: cs, recs, mapConsumption: map } = d;
  const hly = cs.homeLikeYours;
  const items = recs.map((h) => ({ value: h.kwh, weight: h.weight }));
  const pctRows = [5, 10, 20, 25, 30, 40, 50, 60, 70, 75, 80, 90, 95].map((p) => [`P${p}`, fmtNum(weightedPercentile(items, p / 100))]);
  const any: HomeAnswers = { sqft: "any", type: "any", fuel: "any", members: "any" };
  const band = (a: HomeAnswers, label: string) => {
    const e = estimateHome(recs, a, 1);
    return e.n < MIN_HOMES
      ? [label, "—", "—", "—", `only ${e.n}, so the estimator falls back to all homes`]
      : [label, fmtNum(e.p10), fmtNum(e.p50), fmtNum(e.p90), String(e.n)];
  };
  const head = ["", "P10 kWh/yr", "Median kWh/yr", "P90 kWh/yr", "Surveyed homes"];
  const bySize = SQFT_BUCKETS.map((b) => band({ ...any, sqft: b }, SQFT_LABELS[b]));
  const byType = Object.entries(HOME_TYPES).map(([k, v]) => band({ ...any, type: Number(k) }, v));
  const byFuel = Object.entries(HEAT_FUELS).map(([k, v]) => band({ ...any, fuel: Number(k) }, v));
  const byMembers = [1, 2, 3, 4, 5].map((n) => band({ ...any, members: n }, n === 5 ? "5 or more people" : `${n} ${n === 1 ? "person" : "people"}`));
  const months = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];
  const monthly = hly.monthlyKwh.map((m) => [months[m.month - 1], fmtNum(m.p10), fmtNum(m.p50), fmtNum(m.p90), fmtNum(cs.typicalAccount.monthlyKwh[m.month - 1]), fmtPct(cs.seasonalShares[m.month - 1], 1)]);
  const { greenMax, greyMax } = map.thresholds;
  return `## How much electricity homes use (Usage tab)

Two populations, shown side by side and never blended: the EIA typical account (all residential accounts in 2025, including apartments and seasonal homes) and RECS 2020 (552 surveyed Massachusetts homes, weighted to represent all homes in the state; one COVID-year survey, so its bands are wide on purpose).

- RECS yearly use, all homes: median ${fmtNum(hly.annualKwh.p50)} kWh, P10–P90 ${fmtNum(hly.annualKwh.p10)}–${fmtNum(hly.annualKwh.p90)} kWh, weighted mean ${fmtNum(hly.annualKwh.mean)} kWh.
- Low / Mid / High for a home's yearly use (the state's weighted thirds): Low ≤ ${fmtNum(greenMax)} kWh < Mid ≤ ${fmtNum(greyMax)} kWh < High. The estimator badges its answer and a typed-in yearly total this way.
- Typical account 2025: ${fmtNum(cs.typicalAccount.annualKwh)} kWh a year.

Where Massachusetts homes fall (weighted percentiles of yearly kWh; "you use more than X% of homes" reads off this table):

${table(["Percentile", "kWh/yr"], pctRows)}

What drives the difference, one answer at a time (the estimator combines answers; for a combination, point visitors to [A home like yours](#/usage)):

By size:
${table(head, bySize)}

By home type:
${table(head, byType)}

By main heating fuel:
${table(head, byFuel)}

By household size:
${table(head, byMembers)}

A year month by month: RECS band = yearly band × the statewide share of each month (EIA 2019–2025); the typical account is EIA 2025.

${table(["Month", "RECS P10 kWh", "RECS median kWh", "RECS P90 kWh", "Typical account 2025 kWh", "Share of the year"], monthly)}`;
}

function levelRegimeSection(d: KnowledgeInputs): string {
  const h = d.hmm;
  const states = [...h.states].sort((a, b) => a.mean - b.mean);
  return `## Low / Mid / High use regimes (Usage tab)

A ${h.n_states}-state Gaussian hidden Markov model over ${h.timeline.length} months of kWh per account (${h.engine}, seed ${h.seed}); states are ordered by mean use. Each month's regime is in the month-by-month table at the end.

${table(
  ["Regime", "Mean kWh per account", "Long-run share of months"],
  states.map((s) => [LEVEL_WORD[s.regime], fmtNum(s.mean), fmtPct(s.stationary_prob)]),
)}`;
}

function rangeRegimeSection(d: KnowledgeInputs): string {
  const r = d.regimes;
  const areas: RegimeArea[] = r.areas;
  const label = (a: RegimeArea) => (a.area === "MA_RES" ? "Homes (statewide residential use per account, monthly, EIA)" : a.area === "MA" ? "MA grid (three zones added, daily, ISO-NE / EIA-930)" : `${a.area}: ${ZONE_NAMES[a.area as keyof typeof ZONE_NAMES]} (daily, ISO-NE / EIA-930)`);
  const blocks = areas.map((a) => {
    const daily = a.unit === "day";
    const when = daily ? dateLabel(a.current.date) : ymLabel(a.current.date.slice(0, 7));
    const lines = [
      `- Latest ${daily ? "day" : "month"}, ${when}: **${RANGE_WORD[a.current.color]}**, ${pctPoints(a.current.pctVsAverage)} vs the 5-year average (usual range ±${fmtNum(a.current.bandPct, 1)}%); below / within / above odds now ${odds(a.current.probs)}.`,
    ];
    if (a.forecast?.length) {
      lines.push(
        `- Next months (below / within / above): ${a.forecast
          .map((f) => `${ymLabel(f.date.slice(0, 7))} ${RANGE_WORD[f.color]} (${odds(f.probs)}${f.method === "long-run-mix" ? ", long-run odds" : ""})`)
          .join("; ")}.`,
      );
    } else {
      lines.push(`- Outlook (below / within / above): ${a.outlook.map((o) => `${o.days} days ${odds(o.probs)}${o.method === "long-run-mix" ? " (long-run odds)" : ""}`).join("; ")}.`);
    }
    lines.push(
      `- Long-run behaviour: ${a.states
        .map((s) => `${RANGE_WORD[s.color]} ${fmtPct(s.shareOfDays)} of ${daily ? "days" : "months"}, lasting about ${fmtNum(s.expectedDurationDays, 1)} days`)
        .join("; ")}.`,
    );
    return `### ${label(a)}\n\n${lines.join("\n")}`;
  });
  const zoneAreas = areas.filter((a) => a.unit === "day");
  const monthsYm = zoneAreas[0].monthly.map((m) => m.ym);
  const share = (a: RegimeArea, ym: string) => {
    const m = a.monthly.find((x) => x.ym === ym);
    return m ? `${fmtPct(m.green)} / ${fmtPct(m.grey)} / ${fmtPct(m.red)}` : "—";
  };
  return `## Below / Within / Above range (Regimes & forecast tab)

- Definition: usual range = ${r.definition.range}. Above range = ${r.definition.red}; Within = ${r.definition.grey}; Below = ${r.definition.green}.
- Method: ${r.method}. Leakage test (no look-ahead): ${r.leakageTest}.
- How to read the outlook: today's state odds carried forward. A tested model of the gap is used only at horizons where it beat the long-run odds in a walk-forward test; otherwise the outlook is the long-run odds. It is not a weather forecast.
${r.notes.map((n) => `- ${n}`).join("\n")}

${blocks.join("\n\n")}

### Share of days below / within / above range, by month (grid zones)

2020–2023 ran mostly within or below the late-2010s range (COVID, efficiency, rooftop solar); load has grown since 2024 (EIA-930).

${table(["Month", ...zoneAreas.map((a) => `${a.area} below / within / above`)], monthsYm.map((m) => [ymLabel(m), ...zoneAreas.map((a) => share(a, m))]))}`;
}

function forecastSection(d: KnowledgeInputs): string {
  const f = d.forecast;
  const c = f.calibration;
  const b = f.backtest;
  const gridThrough = d.regimes.areas.find((a) => a.unit === "day")?.current.date;
  const blocks = f.areas.map((a) => {
    const name = a.area === "MA" ? "Massachusetts (three zones added)" : `${a.area}: ${ZONE_NAMES[a.area]}`;
    const rows = a.months.map((m, i) => [ymLabel(m.ym), fmtNum(m.p10), fmtNum(m.p50), fmtNum(m.p90), fmtNum(a.sameMonthsLastObservedGWh[i])]);
    return `### ${name}\n\nSix-month total: median ${fmtNum(a.total.p50)} GWh, 80% range ${fmtNum(a.total.p10)}–${fmtNum(a.total.p90)} GWh, 90% range ${fmtNum(a.total.p5)}–${fmtNum(a.total.p95)} GWh.\n\n${table(["Month", "P10 GWh", "Median GWh", "P90 GWh", "Same month a year earlier (observed)"], rows)}`;
  });
  return `## Six-month grid load forecast, ${ymLabel(f.horizon[0])} – ${ymLabel(f.horizon[f.horizon.length - 1])} (Regimes & forecast tab)

- What it is: ${fmtNum(f.nPaths)} simulated paths (${f.method}), on daily load observed through ${gridThrough ? dateLabel(gridThrough) : "the latest published day"} (ISO-NE 2017–2023, then EIA-930; refreshed daily). Each path carries the recent load level and its uncertainty. All customer classes (homes and businesses), not a household bill. There is no separate forecast for the homes series.
- ${
    b
      ? `Tested before shown: refit before each of the last ${b.nWinters} winters (${b.winters}) and run on months it had not seen (${b.nMonths} zone-months). The 80% range held the actual ${fmtPct(b.cov80)} of the time (90% range: ${fmtPct(b.cov90)}), the median's error was ${fmtPct(1 - b.maeVsNaive)} smaller than a "same month last year" guess, and six-month totals missed by ${fmtNum(b.totalMaePct, 1)}% on average.`
      : `Tested before shown: fit only on data to ${dateLabel(c.trainEnd)}, then run on two winters it never saw (${c.test}, ${c.nMonths} zone-months). The 80% range held the actual ${fmtPct(c.cov80)} of the time (90% range: ${fmtPct(c.cov90)}), and the median's error was ${fmtPct(1 - c.maeVsNaive)} smaller than a "same month last year" guess.`
  } It is a simulation, never a promise.
${f.notes.map((n) => `- ${n}`).join("\n")}

${blocks.join("\n\n")}`;
}

function townsSection(d: KnowledgeInputs): string {
  const { towns, mapConsumption: map } = d;
  const zoneRows = ZONES.map((z) => {
    const ts = towns.filter((t) => t.zone === z);
    const p20 = ts.reduce((s, t) => s + t.pop2020, 0);
    const p24 = ts.reduce((s, t) => s + t.pop2024, 0);
    return [`${z} (${ZONE_NAMES[z]})`, ts.length, fmtNum(p24), fmtSignedPct(p24 / p20 - 1)];
  });
  const rows = [...towns]
    .sort((a, b) => a.name.localeCompare(b.name))
    .map((t) => [t.name, t.county, t.zone, fmtNum(t.pop2020), fmtNum(t.pop2024), fmtSignedPct(t.pop2024 / t.pop2020 - 1)]);
  return `## Cities and towns (Towns tab)

- What differs by town on the site: the ISO-NE load zone (which decides which zone's grid regime and forecast apply) and population. Zone assignment is approximate (by county in the backend; for example Brookline is counted in SEMA).
- Why the map isn't coloured by usage: there is no verified per-town electricity-use source (RECS 2020 has no town field and EIA-861M is statewide), so the backend gives every town the same modeled level, ${fmtNum(map.towns[0].annualKwhModel)} kWh a year (the statewide RECS median, class Mid), and the site doesn't paint differences that aren't in the data. For a household, use [A home like yours](#/usage).
- Which utility serves a town is not in the data.

${table(["Zone", "Towns", "Population 2024", "Change since 2020"], zoneRows)}

${table(["Town", "County", "Zone", "Pop. 2020", "Pop. 2024", "Change"], rows)}`;
}

function sourcesSection(d: KnowledgeInputs): string {
  const { eia, recs, towns } = d;
  const gridThrough = d.regimes.areas.find((a) => a.unit === "day")?.current.date;
  return `## Sources and limits (Data & methods tab)

Sources:
- U.S. EIA Form EIA-861M: Massachusetts residential revenue, sales, accounts, average price and kWh per account, ${ymLabel(eia[0].ym)} – ${ymLabel(eia[eia.length - 1].ym)} (2026 preliminary).
- Mass.gov DPU "Basic Service Rates" (retrieved 2 Jul 2026): monthly and fixed-option residential rates by utility, 2005 – Jan 2027.
- U.S. EIA Residential Energy Consumption Survey 2020: ${recs.length} Massachusetts homes with yearly kWh, size, heating fuel, home type, household size and survey weight.
- ISO New England (2017 – 2023), then U.S. EIA-930 (2024 – ${gridThrough ? dateLabel(gridThrough) : "latest"}, published ~10 days late) with Open-Meteo temperature: daily load for NEMA, SEMA and WCMA, refreshed daily.
- U.S. Census Bureau: population of the ${towns.length} towns, 2020 and 2024. MassGIS (via the Leventhal Map & Education Center) town boundaries.

Limits worth knowing:
- RECS 2020 is one COVID-year survey of ${recs.length} homes; its bands are wide on purpose.
- EIA revises preliminary months (all of 2026 so far), so recent values can change.
- There is no verified per-town usage data, so towns are never coloured by consumption.
- Grid load includes businesses as well as homes, and EIA publishes it about 10 days late.
- Usual-range regimes don't remove weather: a heat wave above the range counts as Above.
- The forecast simulates zones independently, so the statewide band is probably too narrow.
- Town-to-zone assignment is approximate.
- Dollar figures cover electricity supply only; delivery charges are not modeled.

Outside Watt If (for questions the data can't answer): the customer's bill or utility for account, billing, outage and service questions; Energy Switch Massachusetts (energyswitchma.gov), the state's site for comparing competitive supply offers; Mass Save (masssave.com) for energy-efficiency rebates; Mass.gov DPU for rate filings.`;
}

